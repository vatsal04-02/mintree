#!/usr/bin/env python3
"""Render docs/TEST_EXECUTION_REGISTER.md from docs/test-runs.jsonl + tests/load/results/register.jsonl."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def load(p):
    return [json.loads(l) for l in open(p)] if p.exists() else []


def ms(v):
    return "—" if v is None else f"{v:,.0f}"


def main():
    runs = load(ROOT / "docs/test-runs.jsonl")
    loads = load(ROOT / "tests/load/results/register.jsonl")
    notes = {}
    for n in load(ROOT / "tests/load/results/annotations.jsonl"):
        notes.setdefault(n["label"], []).append(n["note"])
    out = ["# Test Execution Register", "",
           "Generated by `tests/load/render_register.py` from `docs/test-runs.jsonl` (functional runs) and "
           "`tests/load/results/register.jsonl` (load runs). **History is preserved: entries are only ever appended.** "
           "`current` = the latest run of that kind/scenario; older runs stay as `historical`.", "",
           "Rows marked *manual* were back-filled from observations earlier in the same work session (no automatic recorder existed yet).", "",
           "## 1. Functional test runs", "", "| Date (UTC) | Kind | Commit | Passed | Failed | Result | Status | Environment / note |", "|---|---|---|---|---|---|---|---|"]
    latest = {}
    for r in runs:
        latest[r["kind"]] = r["date"]
    for r in runs:
        c = r["commit"] + ("+dirty" if r.get("dirty") else "")
        out.append(f"| {r['date'][:16].replace('T',' ')} | {r['kind']} | `{c}` | {r.get('passed',0)} | {r.get('failed',0) + r.get('error',0)} | **{r['result']}** | "
                   f"{'current' if latest[r['kind']] == r['date'] else 'historical'} | {r['environment']}{' — '+r['note'] if r.get('note') else ''} |")
    out += ["", "## 2. Load / resilience test runs", "",
            "All load runs below were executed on a **shared 4-vCPU sandbox** (k6, API workers, PostgreSQL, RabbitMQ, Celery on one machine). "
            "They are measurements for finding defects and ranking bottlenecks, **not capacity proof**. Durations marked *reduced* are shorter than the plan's spec.", "",
            "| Date (UTC) | Run | Commit | Workers | Clients / params | req/s | read p95 ms | write p95 ms | posting p95 ms | system-fail % | 5xx note | business conflicts | integrity | Status |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    key = lambda r: r["scenario"]
    lat = {}
    for r in loads:
        lat[key(r) + r.get("tag", "")] = r["label"]
    for r in loads:
        if r["scenario"] == "worker_recovery.py":
            out.append(f"| {r['date'][:16].replace('T',' ')} | {r['label']} | `{r['commit']}` | — | {r['jobs']} jobs, {r['chaos_events']} kills | — | — | — | — | — | lost={r['lost']} dup={r['duplicated_effects']} | — | "
                       f"{'OK' if r['ok'] else 'FAIL'} | {'current' if lat[key(r)] == r['label'] else 'historical'} |")
            continue
        env = " ".join(r.get("env", []))
        integ = {None: "n/a", True: "PASS", False: "**FAIL**"}[r.get("integrity_ok")]
        sf = r.get("system_failure_rate")
        out.append(f"| {r['date'][:16].replace('T',' ')} | {r['label']} | `{r['commit']}` | {r['workers']} | {env} | {r['req_per_s']:.0f} | {ms(r['read_p95_ms'])} | {ms(r['write_p95_ms'])} | "
                   f"{ms(r.get('posting_p95_ms'))} | {'—' if sf is None else f'{sf*100:.2f}'} | k6 exit {r['k6_exit']} | {int(r['business_conflicts'] or 0)} | {integ} | "
                   f"{'current' if lat[key(r)] == r['label'] else 'historical'} |")
    if notes:
        out += ["", "### Annotations (append-only; these qualify the rows above)", ""]
        for label, ns in notes.items():
            out += [f"* **{label}** — " + " ".join(ns)]
    out += ["", "Per-run artefacts (metadata: commit, machine, PostgreSQL settings, dataset sizes, workload; k6 summary; Prometheus snapshots; "
            "system CPU/RSS; integrity report; API/publisher/worker logs) are in `tests/load/results/<label>/`.", ""]
    (ROOT / "docs/TEST_EXECUTION_REGISTER.md").write_text("\n".join(out))
    print("rendered", len(runs), "functional and", len(loads), "load entries")


if __name__ == "__main__":
    main()
